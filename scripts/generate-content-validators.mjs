import Ajv from 'ajv';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { CONTENT_SCHEMAS } from '../shared/content/schemas.js';

const ajv = new Ajv({ allErrors: true, strict: true, allowUnionTypes: true, code: { source: true, esm: true } });
addFormats(ajv);
Object.values(CONTENT_SCHEMAS).forEach((schema) => ajv.addSchema(schema));
const exportsByName = Object.fromEntries(Object.entries(CONTENT_SCHEMAS).map(([name, schema]) => [name, schema.$id]));
const banner = '// Generated by scripts/generate-content-validators.mjs. Do not edit manually.\n';
const runtimeImports = "import equalRuntime from 'ajv/dist/runtime/equal.js';\nimport ucs2lengthRuntime from 'ajv/dist/runtime/ucs2length.js';\nimport * as formatsRuntime from 'ajv-formats/dist/formats.js';\nconst equal = equalRuntime.default ?? equalRuntime;\nconst ucs2length = ucs2lengthRuntime.default ?? ucs2lengthRuntime;\nconst fullFormats = formatsRuntime.fullFormats ?? formatsRuntime.default?.fullFormats;\n";
const generated = standaloneCode(ajv, exportsByName)
  .replaceAll('require("ajv/dist/runtime/equal").default', 'equal')
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length')
  .replaceAll('require("ajv-formats/dist/formats").fullFormats', 'fullFormats');
await writeFile(fileURLToPath(new URL('../shared/content/generatedValidators.js', import.meta.url)), `${banner}${runtimeImports}${generated}`);
process.stdout.write(`Generated ${Object.keys(exportsByName).length} CSP-safe content validators.\n`);
